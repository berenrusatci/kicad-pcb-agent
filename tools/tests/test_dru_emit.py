"""Tests for scripts/dru_emit.py — the .kicad_dru emitter.

Ported from pcb-tool-v2's ipc_dru_koprusu.py self-tests (that module had no
test_ file of its own; its checks lived in ``oz_testleri_calistir`` behind a
``__main__`` block).

The three traps below are not style preferences. Each one causes KiCad to
SILENTLY discard the entire rules file while ``kicad-cli pcb drc`` still
exits cleanly, which is the worst possible failure mode for a gate: a green
DRC that enforced nothing.
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from tests._paths import TOOLS  # noqa: F401  (also fixes sys.path)

from scripts import dru_emit as de
from scripts.ipc import clearance as clearance_mod
from scripts.ipc import dfa as dfa_mod
from scripts.ipc import fab_class as fab_class_mod
from scripts.ipc import trace_width as trace_width_mod

TOOL = "scripts/dru_emit.py"


def run_tool(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run([sys.executable, str(TOOLS / TOOL), *args],
                          capture_output=True, text=True, encoding="utf-8")


class ThreeSilentTrapsTest(unittest.TestCase):
    """The whole reason this module exists."""

    def test_trap_1_version_header_is_always_first(self):
        """Without `(version 1)` the ENTIRE file is silently ignored."""
        text = de.render_rules(
            [de.DruRule("T", "A.NetClass == 'X'", "clearance", 0.2)])
        self.assertTrue(text.startswith("(version 1)"))

    def test_trap_1_header_survives_a_header_comment(self):
        text = de.render_rules(
            [de.DruRule("T", "A.NetClass == 'X'", "clearance", 0.2)],
            header="generated by the test")
        self.assertTrue(text.startswith("(version 1)"))

    def test_trap_2_priority_token_is_never_emitted(self):
        """`(priority N)` is not a valid token and silently kills the rule."""
        text = de.render_rules([
            de.DruRule("A", "A.NetClass == 'X'", "clearance", 0.2,
                       order=de.RuleOrder.EXCEPTION),
            de.DruRule("B", "A.NetClass == 'Y'", "clearance", 0.3,
                       order=de.RuleOrder.GENERAL),
        ])
        self.assertNotIn("(priority", text)
        self.assertNotIn("priority", text)

    def test_trap_2_exceptions_are_written_before_general_rules(self):
        """Precedence is FILE ORDER — first matching rule wins."""
        general = de.DruRule("General", "A.NetClass == 'PWR'", "track_width",
                             0.25, order=de.RuleOrder.GENERAL)
        exception = de.exception_rule("J2 Exception", "J2", 0.13)
        text = de.render_rules([general, exception])   # deliberately reversed
        self.assertLess(text.index('"J2 Exception"'), text.index('"General"'))

    def test_trap_2_stable_order_within_a_group(self):
        first = de.DruRule("First", "A.NetClass == 'A'", "clearance", 0.2)
        second = de.DruRule("Second", "A.NetClass == 'B'", "clearance", 0.3)
        text = de.render_rules([first, second])
        self.assertLess(text.index('"First"'), text.index('"Second"'))

    def test_trap_3_comment_character_is_hash_not_semicolon(self):
        text = de.render_rules(
            [de.DruRule("T", "A.NetClass == 'Y'", "clearance", 0.3,
                        comment="a note")])
        self.assertIn("# a note", text)
        self.assertNotIn(";", text)

    def test_trap_3_semicolon_in_name_is_rejected(self):
        with self.assertRaises(ValueError):
            de.DruRule("Bad;Name", "A.NetClass == 'X'", "clearance", 0.2)

    def test_trap_3_semicolon_in_condition_is_rejected(self):
        with self.assertRaises(ValueError):
            de.DruRule("Name", "A.NetClass == 'X';", "clearance", 0.2)

    def test_trap_3_semicolon_is_allowed_inside_a_comment(self):
        """A ';' inside a '#' line is harmless — the line is already a
        comment. Banning it there would be cargo-culting the rule."""
        rule = de.DruRule("T", "A.NetClass == 'X'", "clearance", 0.2,
                          comment="see foo; bar")
        self.assertIn("# see foo; bar", rule.render())

    def test_every_comment_line_keeps_its_hash_prefix(self):
        """A second line without '#' would be parsed as a stray
        s-expression token and take the whole file down."""
        text = de.render_rules(
            [de.DruRule("T", "A.NetClass == 'X'", "clearance", 0.2,
                        comment="line one\nline two")])
        for line in text.splitlines():
            if "line one" in line or "line two" in line:
                self.assertTrue(line.startswith("#"), line)

    def test_newline_in_name_or_condition_is_rejected(self):
        with self.assertRaises(ValueError):
            de.DruRule("Bad\nName", "A.NetClass == 'X'", "clearance", 0.2)
        with self.assertRaises(ValueError):
            de.DruRule("Name", "A.NetClass\n== 'X'", "clearance", 0.2)


class DruRuleTest(unittest.TestCase):
    def test_non_positive_minimum_is_rejected(self):
        for bad in (0.0, -0.1):
            with self.subTest(bad=bad):
                with self.assertRaises(ValueError):
                    de.DruRule("T", "A.NetClass == 'X'", "clearance", bad)

    def test_render_shape(self):
        rule = de.DruRule("My Rule", "A.NetClass == 'PWR'", "track_width", 0.25)
        text = rule.render()
        self.assertIn('(rule "My Rule"', text)
        self.assertIn('(condition "A.NetClass == \'PWR\'")', text)
        self.assertIn("(constraint track_width (min 0.25mm))", text)

    def test_rules_are_separated_by_blank_lines(self):
        text = de.render_rules([
            de.DruRule("A", "A.NetClass == 'A'", "clearance", 0.2),
            de.DruRule("B", "A.NetClass == 'B'", "clearance", 0.3),
        ])
        self.assertIn(")\n\n(rule", text)


class ConverterTest(unittest.TestCase):
    def test_trace_width_converter_is_a_verified_constraint(self):
        result = trace_width_mod.min_trace_width(
            2.0, 10.0, trace_width_mod.LayerType.EXTERNAL)
        rule = de.rule_from_trace_width("PWR", result)
        self.assertEqual(rule.constraint_type, "track_width")
        self.assertIn(rule.constraint_type, de.VERIFIED_CONSTRAINTS)
        self.assertEqual(rule.min_value_mm, result.width_mm)
        self.assertEqual(rule.condition, "A.NetClass == 'PWR'")

    def test_clearance_converter_flags_the_unverified_condition_form(self):
        result = clearance_mod.clearance_mm(
            250, clearance_mod.LayerType.EXTERNAL)
        rule = de.rule_from_clearance("HV", "GND", result)
        self.assertEqual(rule.constraint_type, "clearance")
        self.assertIn("&&", rule.condition)
        self.assertIn("NOT VERIFIED", rule.comment)

    def test_fab_class_converter_emits_only_annular_width(self):
        """Solder-mask dam and aspect ratio have no native KiCad constraint
        and must NOT silently appear here."""
        limits = fab_class_mod.CLASS_LIMITS[fab_class_mod.FabClass.CLASS_2]
        rules = de.rules_from_fab_class(limits)
        self.assertEqual(len(rules), 1)
        self.assertEqual(rules[0].constraint_type, "annular_width")
        self.assertEqual(rules[0].min_value_mm, limits.min_annular_ring_mm)

    def test_dfa_converter_is_an_exception_and_is_flagged_unverified(self):
        size = dfa_mod.PackageSize(2.0, 1.25, 0.6)
        target = dfa_mod.minimum_clearance(
            dfa_mod.ComponentType.SMD_PASSIVE, dfa_mod.ComponentType.SMD_IC,
            size, size)
        rule = de.rule_from_dfa("R1", "U1", target)
        self.assertEqual(rule.order, de.RuleOrder.EXCEPTION)
        self.assertEqual(rule.constraint_type, "courtyard_clearance")
        self.assertNotIn(rule.constraint_type, de.VERIFIED_CONSTRAINTS)
        self.assertIn("NOT VERIFIED", rule.comment)

    def test_three_w_converter_uses_edge_to_edge(self):
        """Confusing edge-to-edge with centre-to-centre is the most common
        3W mistake; KiCad clearance is edge-to-edge."""
        class FakeResult:
            min_edge_to_edge_mm = 0.6
            min_center_to_center_mm = 0.8
        rule = de.rule_from_three_w("CLK", "DATA", FakeResult())
        self.assertEqual(rule.min_value_mm, 0.6)

    def test_three_w_converter_accepts_the_real_emc_rules_target(self):
        """Integration pin: emc_rules.ThreeWTarget must satisfy the duck
        type. If that class is renamed, this fails instead of the rule
        silently never being emitted."""
        from scripts.emc_rules import three_w
        target = three_w(0.2)
        rule = de.rule_from_three_w("CLK", "DATA", target)
        self.assertEqual(rule.min_value_mm, target.min_edge_to_edge_mm)
        self.assertLess(rule.min_value_mm, target.min_center_to_center_mm)

    def test_three_w_converter_refuses_a_result_without_edge_to_edge(self):
        class Missing:
            min_center_to_center_mm = 0.8
        with self.assertRaises(ValueError):
            de.rule_from_three_w("CLK", "DATA", Missing())

    def test_exception_rule_matches_a_single_reference(self):
        rule = de.exception_rule("J2", "J2", 0.13)
        self.assertEqual(rule.condition,
                         "A.Reference == 'J2' && B.Reference == 'J2'")
        self.assertEqual(rule.order, de.RuleOrder.EXCEPTION)


class SpecTest(unittest.TestCase):
    SPEC = {
        "name_prefix": "TEST ",
        "header": "generated by the test suite",
        "track_width": [{"net_class": "PWR", "current_a": 2.0}],
        "clearance": [{"net_class_a": "HV", "net_class_b": "GND",
                       "voltage_v": 250}],
        "annular_ring": {"class": "Class 3"},
        "exceptions": [{"name": "J2 exception", "ref": "J2", "min_mm": 0.13}],
    }

    def test_spec_builds_every_section(self):
        rules = de.rules_from_spec(self.SPEC)
        self.assertEqual(len(rules), 4)
        self.assertEqual(
            {rule.constraint_type for rule in rules},
            {"track_width", "clearance", "annular_width"})

    def test_name_prefix_is_applied(self):
        for rule in de.rules_from_spec(self.SPEC):
            if rule.order is de.RuleOrder.GENERAL:
                self.assertTrue(rule.name.startswith("TEST "), rule.name)

    def test_empty_spec_produces_no_rules(self):
        self.assertEqual(de.rules_from_spec({}), [])

    def test_non_object_spec_is_rejected(self):
        with self.assertRaises(ValueError):
            de.rules_from_spec([])


class WriteFileTest(unittest.TestCase):
    def test_empty_rule_list_is_refused(self):
        """An empty .kicad_dru would hide 'no rules wanted' behind
        'rules forgotten'."""
        with tempfile.TemporaryDirectory() as tmp:
            with self.assertRaises(ValueError):
                de.write_rules_file(Path(tmp) / "x.kicad_dru", [])

    def test_existing_file_is_backed_up(self):
        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "board.kicad_dru"
            target.write_text("original", encoding="utf-8")
            de.write_rules_file(
                target, [de.DruRule("T", "A.NetClass == 'X'", "clearance", 0.2)])
            backup = target.with_suffix(target.suffix + ".bak")
            self.assertTrue(backup.is_file())
            self.assertEqual(backup.read_text(encoding="utf-8"), "original")

    def test_backup_can_be_disabled(self):
        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "board.kicad_dru"
            target.write_text("original", encoding="utf-8")
            de.write_rules_file(
                target, [de.DruRule("T", "A.NetClass == 'X'", "clearance", 0.2)],
                backup=False)
            self.assertFalse(
                target.with_suffix(target.suffix + ".bak").exists())

    def test_file_is_overwritten_not_appended(self):
        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "board.kicad_dru"
            rule = [de.DruRule("T", "A.NetClass == 'X'", "clearance", 0.2)]
            de.write_rules_file(target, rule)
            de.write_rules_file(target, rule)
            self.assertEqual(
                target.read_text(encoding="utf-8").count("(version 1)"), 1)

    def test_written_file_is_utf8(self):
        with tempfile.TemporaryDirectory() as tmp:
            target = Path(tmp) / "board.kicad_dru"
            de.write_rules_file(
                target,
                [de.DruRule("T", "A.NetClass == 'X'", "clearance", 0.2,
                            comment="Türkçe açıklama")])
            self.assertIn("Türkçe açıklama",
                          target.read_text(encoding="utf-8"))


class CliContractTest(unittest.TestCase):
    SPEC = SpecTest.SPEC

    def test_missing_positional_input_exits_2(self):
        proc = run_tool()
        self.assertEqual(proc.returncode, 2, proc.stderr)
        self.assertEqual(proc.stdout, "")

    def test_self_test_is_opt_in_and_writes_to_stderr(self):
        proc = run_tool("--self-test")
        self.assertEqual(proc.returncode, 0, proc.stderr)
        self.assertIn("SELF-TEST PASS", proc.stderr)
        self.assertEqual(proc.stdout, "")

    def test_stdout_is_json_and_the_file_is_written(self):
        with tempfile.TemporaryDirectory() as tmp:
            tmpdir = Path(tmp)
            spec = tmpdir / "spec.json"
            spec.write_text(json.dumps(self.SPEC), encoding="utf-8")
            out = tmpdir / "board.kicad_dru"
            proc = run_tool(str(spec), "--out", str(out))
            self.assertEqual(proc.returncode, 0, proc.stderr)
            report = json.loads(proc.stdout)
            self.assertEqual(report["schema_version"], "dru-emit-report/v1")
            self.assertEqual(report["rule_count"], 4)
            self.assertTrue(out.is_file())
            self.assertTrue(
                out.read_text(encoding="utf-8").startswith("(version 1)"))

    def test_report_marks_unverified_rules(self):
        with tempfile.TemporaryDirectory() as tmp:
            spec = Path(tmp) / "spec.json"
            spec.write_text(json.dumps(self.SPEC), encoding="utf-8")
            report = json.loads(run_tool(str(spec)).stdout)
            self.assertTrue(report["unverified_two_net_class_rules"])
            self.assertTrue(report["limits"])
            verified = {rule["name"]: rule["verified_constraint"]
                        for rule in report["rules"]}
            self.assertTrue(any(verified.values()))

    def test_warnings_go_to_stderr_not_stdout(self):
        with tempfile.TemporaryDirectory() as tmp:
            spec = Path(tmp) / "spec.json"
            spec.write_text(json.dumps(self.SPEC), encoding="utf-8")
            proc = run_tool(str(spec))
            self.assertIn("WARNING", proc.stderr)
            json.loads(proc.stdout)          # stdout stays pure JSON

    def test_a_spec_producing_no_rules_exits_2(self):
        with tempfile.TemporaryDirectory() as tmp:
            spec = Path(tmp) / "spec.json"
            spec.write_text("{}", encoding="utf-8")
            proc = run_tool(str(spec))
            self.assertEqual(proc.returncode, 2, proc.stderr)

    def test_malformed_json_exits_2(self):
        with tempfile.TemporaryDirectory() as tmp:
            spec = Path(tmp) / "spec.json"
            spec.write_text("{not json", encoding="utf-8")
            self.assertEqual(run_tool(str(spec)).returncode, 2)

    def test_json_flag_writes_the_report(self):
        with tempfile.TemporaryDirectory() as tmp:
            tmpdir = Path(tmp)
            spec = tmpdir / "spec.json"
            spec.write_text(json.dumps(self.SPEC), encoding="utf-8")
            out = tmpdir / "report.json"
            proc = run_tool(str(spec), "--json", str(out))
            self.assertEqual(proc.returncode, 0, proc.stderr)
            self.assertEqual(json.loads(out.read_text(encoding="utf-8")),
                             json.loads(proc.stdout))


